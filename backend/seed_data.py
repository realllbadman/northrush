"""Catalog seed data for NorthRush Outdoors.

Every product is a self-contained dict. ``image`` is either a bare filename
(served from static/images/) or a full http(s) URL. Edit a product here and
restart — sync_products() upserts the catalog and prunes anything removed.
Orders/bookings live in separate tables and are never touched.
"""
import json
import os

from backend.models import Product

IMAGES_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "static", "images"
)


def _img(name):
    """Full URL as-is; bare filename if it exists in static/images/; else placeholder."""
    if not name:
        return "placeholder.jpg"
    if name.startswith("http://") or name.startswith("https://"):
        return name
    return name if os.path.exists(os.path.join(IMAGES_DIR, name)) else "placeholder.jpg"


_FIELDS = ("name", "brand", "category", "subcategory", "model_number", "price",
           "price_max", "original_price", "description", "features", "in_stock",
           "badge", "image", "images")


def _normalize(p):
    """Fill defaults + resolve images for the ORM.

    ``images`` is the editable per-product URL list. ``image`` (the first one,
    or the placeholder when the list is empty) is what cards/listing/cart use.
    """
    raw = p.get("images")
    if raw is None:                       # backward-compat single "image"
        one = p.get("image")
        raw = [one] if one else []
    imgs = [_img(u) for u in raw if u]
    return {
        "slug": p["slug"],
        "name": p.get("name", ""),
        "brand": p.get("brand", ""),
        "category": p.get("category", ""),
        "subcategory": p.get("subcategory", ""),
        "model_number": p.get("model_number", ""),
        "price": float(p.get("price") or 0),
        "price_max": p.get("price_max"),
        "original_price": p.get("original_price"),
        "description": p.get("description", ""),
        "features": list(p.get("features") or []),
        "in_stock": 1 if p.get("in_stock", 1) else 0,
        "badge": p.get("badge"),
        "image": imgs[0] if imgs else "placeholder.jpg",
        "images": imgs,
    }


